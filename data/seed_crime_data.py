# ── Tuning knobs ──────────────────────────────────────────────────────────────

# Target count range per zone for 12 months
INCIDENT_COUNT = {"peenya": 900, "subramanyapura": 700}

INCIDENT_TYPES = [
    "harassment",
    "stalking",
    "eve_teasing",
    "chain_snatching",
    "robbery",
    "assault",
    "suspicious_activity",
]

