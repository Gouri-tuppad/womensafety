"""
data/seed_crime_data.py - Generate SYNTHETIC crime incidents for SafeWay zones.

ALL data generated by this script is SOURCE="synthetic" and clearly flagged.
It must NEVER be presented as real crime data.

Correlations modelled (documented assumptions):
  - Darkness: incidents increase after civil sunset and peak 21:00-02:00.
  - Isolation: industrial / compound-wall segments, blank-wall stretches, vacant plots.
  - Peenya specifics: long industrial road stretches between factory gates, isolated
    segments after the last shift change (~23:00), garment-unit side lanes.
  - Subramanyapura specifics: interior lanes, lake/park edges, vacant plots,
    poorly-lit residential alleys after 22:00.
  - Weekly: Friday/Saturday nights have 30 % uplift; Sunday mornings have low risk.
  - Monthly: spread over past 12 months with mild seasonal variation.

Also accepts a real CSV with columns: lat, lon, type, severity, timestamp, source
via the make target: make seed CSV=path/to/file.csv

Usage:
    python -m data.seed_crime_data               # ZONE from env
    python -m data.seed_crime_data peenya
    python -m data.seed_crime_data subramanyapura
    python -m data.seed_crime_data peenya --csv incidents.csv
"""

